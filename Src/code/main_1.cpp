#include <iostream>
#include <string>

#include <Until/Input.hpp>

// ============================================================================
// 1. ЗАДАНИЕ 1. НАИВНАЯ ХЭШ-ФУНКЦИЯ ДЛЯ СТРОКИ
// ============================================================================

/**
 * @brief Рассчитывает хэш строки наивным алгоритмом (суммированием кодов всех символов).
 * 
 * @param s Входная строка.
 * @return int Целочисленное значение наивного хэша.
 */
int simple_string_hash(const std::string& s) {
    int hash = 0;
    for (char ch : s) {
        hash += static_cast<unsigned char>(ch);
    }
    return hash;
}

// ============================================================================
// 2. ТЕСТИРОВАНИЕ И MAIN
// ============================================================================

int main() {
   std::cout << "========================================================================================\n";
    std::cout << "                   ДОМАШНЕЕ ЗАДАНИЕ: ХЕШИРОВАНИЕ (ЗАДАНИЕ 1)                             \n";
    std::cout << "========================================================================================\n\n";

    std::string input;

    do {
        // Безопасный ввод строки через функцию get_input (длина от 1 до max)
        input = get_input<std::string>("Введите строку [exit => выход из программы]: ", 1);

        int hash_value = simple_string_hash(input);
        std::cout << "Наивный хэш строки " << input << " = " << hash_value << "\n";

    } while (input != "exit");

    std::cout << "\n========================================================================================\n";
    std::cout << "Работа программы завершена.\n";
    std::cout << "========================================================================================\n";

    return 0;
}