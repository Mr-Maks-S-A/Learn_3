/**
 * @brief Выводит элементы целочисленного массива в консоль.
 * 
 * @param arr Указатель на исходный массив.
 * @param size Размер массива.
 */
void print_array(const int* arr, int size) {
    for (int i = 0; i < size; ++i) {
        std::cout << arr[i] << (i == size - 1 ? "" : " ");
    }
    std::cout << "\n";
}

/**
 * @brief Вычисляет уровень (глубину) узла в пирамиде по его индексу.
 * 
 * @param index Индекс узла в массиве (начиная с 0).
 * @return int Уровень узла (корень находится на уровне 0).
 */
int get_node_level(int index) {
    if (index <= 0) return 0;
    return static_cast<int>(std::log2(index + 1));
}

/**
 * @brief Выводит текстовую информацию об одном узле пирамиды.
 * 
 * @param arr Указатель на массив пирамиды.
 * @param index Индекс выводимого узла.
 */
void print_node(const int* arr, int index) {
    int level = get_node_level(index);

    if (index == 0) {
        std::cout << level << " root " << arr[0];
        return;
    }

    int parent_index = (index - 1) / 2;
    int parent_val = arr[parent_index];

    if (index % 2 != 0) {
        // Нечётный индекс — левый потомок
        std::cout << level << " left(" << parent_val << ") " << arr[index];
    } else {
        // Чётный индекс — правый потомок
        std::cout << level << " right(" << parent_val << ") " << arr[index];
    }
}

// ============================================================================
// 1. ЗАДАНИЕ 1. ВЫВОД ПИРАМИДЫ НА МАССИВЕ
// ============================================================================

/**
 * @brief Выводит всю пирамиду на экран постранично по каждому узлу.
 * 
 * @param arr Указатель на массив элементов пирамиды.
 * @param size Размер массива.
 */
void print_pyramid(const int* arr, int size) {
    if (arr == nullptr || size <= 0) return;

    std::cout << "Пирамида:\n";
    for (int i = 0; i < size; ++i) {
        print_node(arr, i);
        std::cout << "\n";
    }
}

// ============================================================================
// 2. ЗАДАНИЕ 2. ПУТЕШЕСТВИЕ ПО ПИРАМИДЕ
// ============================================================================

/**
 * @brief Запускает интерактивный режим навигации по узлам пирамиды.
 * 
 * @details Навигация осуществляется с помощью функции безопасного ввода get_input.
 *  Допустимые команды:
 *  - "up": перейти к родителю
 *  - "left": перейти к левому потомку
 *  - "right": перейти к правому потомку
 *  - "exit": завершить навигацию
 * 
 * @param arr Указатель на массив элементов пирамиды.
 * @param size Размер массива.
 */
void travel_pyramid(const int* arr, int size) {
    if (arr == nullptr || size <= 0) return;

    int current_index = 0;

    while (true) {
        std::cout << "Вы находитесь здесь: ";
        print_node(arr, current_index);
        std::cout << "\n";

        // Получение гарантированно валидной команды с помощью вашего get_input
        std::string command = get_input<std::string>(
            "Введите команду (up / left / right / exit): ",
            {"up", "left", "right", "exit"}
        );

        if (command == "exit") {
            break;
        } 
        
        if (command == "up") {
            if (current_index == 0) {
                std::cout << "Ошибка! Отсутствует родитель\n";
            } else {
                current_index = (current_index - 1) / 2;
                std::cout << "ОК\n";
            }
        } else if (command == "left") {
            int left_child_index = 2 * current_index + 1;
            if (left_child_index >= size) {
                std::cout << "Ошибка! Отсутствует левый потомок\n";
            } else {
                current_index = left_child_index;
                std::cout << "ОК\n";
            }
        } else if (command == "right") {
            int right_child_index = 2 * current_index + 2;
            if (right_child_index >= size) {
                std::cout << "Ошибка! Отсутствует правый потомок\n";
            } else {
                current_index = right_child_index;
                std::cout << "ОК\n";
            }
        }
    }
}

